/* ============================================================
   ПЕРЕИЗДАНИЕ ЛИ ЭТО
   ------------------------------------------------------------
   Отдельный файл, а не функция внутри years.mjs, по одной причине:
   его нужно проверять тестами, а years.mjs при импорте сразу идёт
   в Spotify.

   Зачем вообще. У Spotify дата альбома — это дата ИЗДАНИЯ, а не
   написания песни. Пока речь про обычный альбом, разницы нет. Но
   если запись живая, ремастеренная или собрана в юбилейный сборник,
   дата уезжает на годы вперёд: «Led Zeppelin — No Quarter» с
   «Mothership (Remastered)» датирована 2007-м вместо 1973-го, а
   «Ado — Basket Worm» с концертника — 2026-м.

   Само по себе это ещё не приговор: у половины ремастеров Spotify
   честно держит дату оригинала («Queen — Killer Queen» с «Sheer
   Heart Attack (Deluxe Edition 2011 Remaster)» — 1974-й, как и
   надо). Поэтому функция не выносит вердикт «год неверный», а
   только говорит «этой дате верить на слово нельзя, сверься
   поиском».
   ============================================================ */

/* Концертная запись. Просто слова «live» мало: оно сидит в названиях
   «Date A Live» и «『ウマ娘』WINNING LIVE 14», где ничего живого нет.
   Поэтому либо оборот «Live At/From/In/On», либо «live» обособленное
   скобкой, тире или концом строки — так Spotify помечает версию. */
const КОНЦЕРТ = [
  /(^|[\s(\[–—-])live\s+(at|from|in|on)\b/i,
  /[(\[]\s*live\s*[)\]]/i,
  /[-–—]\s*live\s*$/i
];

/* Переиздание того же исполнения: ремастер, перезапись, юбилейное
   издание. «Remixed & Remastered» ловится тем же «remaster». */
const ПЕРЕИЗДАНО = [
  /\bremaster/i,
  /\bre-?record/i,
  /'?s version\b/i,            // Taylor's Version и родня
  /\banniversary\b/i
];

/* Сборники, которые Spotify не помечает как compilation. Японские
   «BEST SELECTION» и «Early BEST Collection» приезжают обычным
   альбомом, и дата у них — год сборника: «Yuki Kajiura — El Cazador»
   получила 2023-й вместо 2007-го. Ищем только в названии альбома:
   в названии песни «best» — это просто слово. */
const СБОРНИК_ПО_ИМЕНИ = [
  /\bbest\s+(of|selection|collection|album)\b/i,
  /\bgreatest\s+hits\b/i,
  /\bthe\s+best\b/i
];

const любое = (список, s) => !!s && список.some(re => re.test(s));

/* name — название трека у Spotify, album — название его альбома.
   Оба могут быть пустыми: тогда судить не по чему и ответ «нет». */
export function переиздание(name, album) {
  const n = String(name || ''), a = String(album || '');
  return любое(КОНЦЕРТ, n) || любое(КОНЦЕРТ, a)
      || любое(ПЕРЕИЗДАНО, n) || любое(ПЕРЕИЗДАНО, a)
      || любое(СБОРНИК_ПО_ИМЕНИ, a);
}
