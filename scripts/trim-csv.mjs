/* ============================================================
   ОБРЕЗКА ЛИШНИХ КОЛОНОК
   ------------------------------------------------------------
   В октябре 2026 в таблице появились колонки с пересказами треков
   и оценками популярности — «Три интересных факта», «О чём трек?»
   и прочие. Сайт их не читает, а весят они много: выгрузка разом
   выросла с 1,7 до 18,4 МБ. Этот файл качает каждый, кто открыл
   страницу, и на телефоне разница заметна.

   Поэтому в data.csv едут ровно те колонки, которые встречаются
   в коде — в js/, scripts/ и bot/. Появится новая нужная — её надо
   дописать в KEEP, иначе она не доедет.

   Отдельным файлом, а не внутри fetch-sheet.mjs: тот при импорте
   сразу лезет в сеть, и проверкам его не достать.
   ============================================================ */

export const KEEP = ['Что', 'Где', 'Когда', 'Кто', 'Тип',
  'Оценка', 'Откуда', 'Тэги', 'Жанр', 'Фича'];

/* Порядок строк не меняется: в нём держится весь архив — строки-
   разделители стримов идут сверху вниз, и сортировать его нельзя. */
export function обрезать(text, P) {
  const r = P.parse(text, { header: true, skipEmptyLines: 'greedy' });
  const есть = KEEP.filter(k => (r.meta.fields || []).includes(k));
  const строки = [];
  for (const с of r.data) {
    const o = {};
    let пусто = true;
    for (const k of есть) {
      o[k] = с[k] == null ? '' : String(с[k]);
      if (o[k].trim()) пусто = false;
    }
    // Строка, пустая во всех нужных колонках, — остаток чужой колонки:
    // ни трека, ни оценки, ни разделителя стрима в ней нет.
    if (!пусто) строки.push(o);
  }
  return P.unparse(строки, { columns: есть, newline: '\n' }) + '\n';
}
