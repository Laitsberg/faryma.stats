/* ============================================================
   ОЧЕРЕДЬ НА РАЗНОС (queue.html)
   ------------------------------------------------------------
   Показывает, что уже принесли на ближайший стрим.

   Данные берутся у бота, а не у Гугла напрямую: очередь заполняют
   прямо во время стрима, и браузеру Гугл выгрузку с чужого домена
   читать не даст. Бот же держит её минуту и обновляет сам.

   Ничего здесь не считается сверх того, что видно в списке. Ни
   «твой трек будет N-м», ни «до тебя столько-то часов»: сайт не
   знает, какой сегодня стрим и в каком порядке пойдут типы. Всё,
   что тут написано цифрами, — это счёт строк, лежащих рядом.
   ============================================================ */

/* Пока страница открыта, список сам подтягивается: во время стрима
   он меняется каждые несколько минут, а человек держит вкладку. */
const ОБНОВЛЯТЬ_МС = 60_000;

let ЗАЯВКИ = [];
let ВИД = '';          // выбранный вид или пусто — показывать все

const $ = id => document.getElementById(id);
const число = n => n.toLocaleString('ru-RU');
/* plural() приходит из js/util.js — общий для всех страниц */

/* Цвет вида. Шкалу оценок не трогаем — там цвет значит ступень,
   и путать их нельзя. Долги все одного цвета: их девять сортов,
   и девять оттенков превратили бы список в радугу. */
const ЦВЕТА = {
  донат:  '#F2660F',
  заказ:  '#4CC3C9',
  повтор: '#C8B08A',
  долг:   '#F0A02A',
  прочее: '#A0A0A8'
};
const цвет = вид => ЦВЕТА[вид] || ЦВЕТА.прочее;

/* ---------- отрисовка ---------- */

function цифры() {
  const по = вид => ЗАЯВКИ.filter(з => з.вид === вид).length;
  const k = [
    [число(ЗАЯВКИ.length), 'заявок в списке'],
    [число(по('донат')),   'донатов'],
    [число(по('заказ')),   'заказов'],
    [число(по('долг')),    'долгов']
  ];
  $('qKpis').innerHTML = k.map(([n, l]) =>
    `<div class="kpi"><div class="n">${n}</div><div class="l">${esc(l)}</div></div>`).join('');
}

/* Виды в том порядке, в каком их разбирают: донат, потом долги от
   большего множителя к меньшему, потом всё остальное. «Долг» без
   множителя приходит от бота уже как «долг ×1», поэтому отдельного
   правила для него тут не нужно — он встаёт последним сам. */
function виды() {
  const счёт = new Map();
  for (const з of ЗАЯВКИ) {
    const к = счёт.get(з.тип) || { тип: з.тип, вид: з.вид, кратность: з.кратность, n: 0 };
    к.n++; счёт.set(з.тип, к);
  }
  const вес = в => ({ донат: 0, долг: 1, заказ: 2, повтор: 3 })[в] ?? 4;
  return [...счёт.values()].sort((a, b) =>
    вес(a.вид) - вес(b.вид) ||
    (b.кратность ?? -1) - (a.кратность ?? -1) ||
    a.тип.localeCompare(b.тип, 'ru'));
}

function лесенка() {
  const список = виды();
  const макс = Math.max(...список.map(в => в.n), 1);
  $('qLadder').innerHTML = список.map(в => {
    const выбран = ВИД === в.тип;
    return `<button class="rung${выбран ? ' on' : ''}" data-vid="${esc(в.тип)}" type="button">` +
      `<span class="nm">${esc(в.тип)}</span>` +
      `<span class="track"><span class="fill" style="width:${в.n / макс * 100}%;` +
        `background:${цвет(в.вид)}"></span></span>` +
      `<span class="val">${число(в.n)}</span></button>`;
  }).join('');
}

/* Что показывать в колонке «Трек». В таблице там вперемешку
   человеческие названия и голые ссылки — на ссылку название не
   выдумываем, а честно пишем, куда она ведёт. */
function трек(что) {
  const ссылка = parseLink(что);
  if (!ссылка) return esc(что);
  const виден = что.trim() === ссылка.url || /^https?:\/\//i.test(что.trim());
  const подпись = виден ? `ссылка · ${ссылка.platform}` : что;
  return `<a class="tlink" href="${esc(ссылка.url)}" target="_blank" ` +
    `rel="noopener noreferrer">${esc(подпись)}</a>`;
}

function строки() {
  const видно = ВИД ? ЗАЯВКИ.filter(з => з.тип === ВИД) : ЗАЯВКИ;
  $('qRows').innerHTML = видно.map(з =>
    `<tr>` +
      `<td class="num mono">${з.н}</td>` +
      `<td><span class="pill" style="color:${цвет(з.вид)}">${esc(з.тип)}</span></td>` +
      `<td>${трек(з.что)}</td>` +
      `<td class="mono">${esc(з.кто || '—')}</td>` +
      `<td>${esc(з.инфа || '')}</td>` +
    `</tr>`).join('');

  $('qCount').textContent = ВИД
    ? `${число(видно.length)} ${plural(видно.length, 'заявка', 'заявки', 'заявок')} вида «${ВИД}»`
    : `${число(видно.length)} ${plural(видно.length, 'заявка', 'заявки', 'заявок')} — весь список`;
  $('qState').textContent = ВИД ? `показаны только: ${ВИД}` : 'показаны все';
  if (typeof markScrollables === 'function') markScrollables();
}

function нарисовать(д) {
  ЗАЯВКИ = д.треки || [];
  $('qBoot').hidden = true;
  $('qErr').hidden = true;
  $('qApp').hidden = false;

  const метка = $('streamTag');
  if (д.стрим) { метка.hidden = false; метка.textContent = `стрим на ${д.стрим}`; }
  else метка.hidden = true;

  цифры(); лесенка(); строки();
}

function беда(текст) {
  $('qBoot').hidden = true;
  // Если список уже показан, старый оставляем: он хотя бы был правдой
  // минуту назад, а пустая страница не лучше несвежей.
  if (!$('qApp').hidden) return;
  $('qErr').hidden = false;
  $('qErrText').textContent = текст;
}

/* ---------- загрузка ---------- */

async function прочитать() {
  const адрес = (typeof QUEUE_URL !== 'undefined' && QUEUE_URL) || '';
  if (!адрес) return беда('Адрес очереди не задан в js/config.js.');
  try {
    const r = await fetch(адрес, { cache: 'no-store' });
    const д = await r.json();
    if (!r.ok || д.беда)
      return беда('Очередь сейчас не читается: ' + (д.беда || `ответ ${r.status}`) +
        '. Список берётся из таблицы через бота — если бот спит, страница пустая.');
    нарисовать(д);
  } catch (e) {
    беда('Не получилось связаться с ботом, который читает таблицу: ' + e.message);
  }
}

/* ---------- события ---------- */

document.addEventListener('click', e => {
  const кн = e.target.closest('.rung[data-vid]');
  if (кн) {
    // повторное нажатие снимает отбор — как на шкале главной страницы
    ВИД = ВИД === кн.dataset.vid ? '' : кн.dataset.vid;
    лесенка(); строки();
    return;
  }
  if (e.target.closest('#qReset')) { ВИД = ''; лесенка(); строки(); }
});

прочитать();
setInterval(прочитать, ОБНОВЛЯТЬ_МС);
