/* ============================================================
   ОЧЕРЕДЬ НА РАЗНОС — РАЗБОР ЛИСТА
   ------------------------------------------------------------
   Настоящий лист отсюда не прочитать, поэтому проверяем разбор на
   выдуманном, повторяющем строение живого: сначала строка колонок,
   потом объявления и список донатеров, и только потом заявки.

   Главное, что тут стережётся, — цены. Колонка в листе есть, а в
   ответе её быть не должно ни под каким видом.
   ============================================================ */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { papa } from './helpers.mjs';
import { разобрать, разобратьТип } from '../bot/queue.mjs';

/* Лист устроен неудобно, и это не выдумка: строка колонок стоит
   первой, а под ней ещё десяток строк объявлений — их надо
   пропустить, не приняв за заявки. */
const ЛИСТ = [
  'Что,Кто,Тип,Цена,Оценка,Откуда,Жанр,Фича,Доп. инфа',
  '"ВНИМАНИЕ!!! ЗАКАЗ НОВЫХ ТРЕКОВ ОТ 2000Р!!!",,,,,,,,',
  ',,,,Стрим на 5.09.2026г.,,,,',
  '"Порядок треков на стриме: Донат → Долг x8 → Донат → Долг x7 →…",,,,,,,,',
  '"Оt Oldfanmusic - 500р, takao_yamataki - 1000р",,,,,,,,',
  ',,,,,,,,',
  'Fläschbänkler - das letzte Alphorn,Rtur,донат,"р.2 222",,,,,Комментарий',
  'IKUO - Believer,DzenDish,ДОНАТ,"р.2 200",,,,,',
  'Clair Obscur: Expedition 33,takao_yamataki,заказ,"р.1 000",,Игра,поп / баллада,,',
  'Cocho Cocho,WalkingSpeed,повтор,"р.2 000",,,,,"Трек уже был"',
  'OxT - MASS FOR THE DEAD,DzenDish,долг х8,"р.1 100",,Игра,,,',
  'Krol - Green Flash,Sheruka,Долг X7,"р.1 000",,,фанк,,',
  'Kagen no Tsuki,Kipyatocheck,долг x 6,"р.1 000",,,,,Комментарий',
  ',,,,,,,,',
  ',,,,,,,,'
].join('\n');

test('разбор очереди: шапка находится, объявления отсеиваются', () => {
  const д = разобрать(ЛИСТ, papa());
  assert.equal(д.всего, 7, 'в очередь попало не семь заявок');
  assert.equal(д.стрим, '5.09.2026', 'дата стрима не вычитана из шапки');
  // строки-объявления типа не имеют и до списка доходить не должны
  assert.ok(!д.треки.some(т => /ВНИМАНИЕ|Порядок треков|Oldfanmusic/.test(т.что)),
    'объявление приняли за заявку');
});

test('цены не выходят из бота ни в каком виде', () => {
  const д = разобрать(ЛИСТ, papa());
  const всё = JSON.stringify(д);
  // в листе цены записаны как «р.2 222» — ни числа, ни колонки быть не должно
  assert.ok(!/2\s?222|2\s?200|1\s?100/.test(всё), 'в ответе нашлась сумма из листа');
  assert.ok(!/цена/i.test(всё), 'в ответе нашлась колонка цены');
  for (const т of д.треки)
    assert.ok(!('цена' in т), `у заявки «${т.что}» осталось поле цены`);
});

test('долг читается с любой буквой «икс» и с пробелом', () => {
  // в таблице вперемешку кириллическая «х» и латинская «x»
  for (const [сырой, кратность] of [
    ['долг х8', 8], ['Долг X7', 7], ['долг x 6', 6], ['ДОЛГ Х12', 12]
  ]) {
    const т = разобратьТип(сырой);
    assert.equal(т.вид, 'долг', `«${сырой}» не признан долгом`);
    assert.equal(т.кратность, кратность, `«${сырой}»: не та кратность`);
    assert.equal(т.подпись, `долг ×${кратность}`);
  }
});

test('остальные типы узнаются независимо от регистра', () => {
  assert.equal(разобратьТип('ДОНАТ').вид, 'донат');
  assert.equal(разобратьТип('заказ').вид, 'заказ');
  assert.equal(разобратьТип('Повтор').вид, 'повтор');
  assert.equal(разобратьТип(''), null, 'пустой тип должен отсеивать строку');
  // «долг» без множителя в листе есть, и это долг, а не непонятное слово.
  // Кратность при этом пустая: чему он равен, никто не говорил
  const голый = разобратьТип('долг');
  assert.equal(голый.вид, 'долг');
  assert.equal(голый.кратность, null, '«долгу» без множителя приписали число');
  assert.equal(голый.подпись, 'долг');
  // незнакомое слово не выбрасываем, а показываем как есть: в листе
  // заводят новые типы, и молча терять заявку хуже, чем показать
  assert.equal(разобратьТип('лотерея').вид, 'прочее');
  assert.equal(разобратьТип('лотерея').подпись, 'лотерея');
});

test('порядок заявок сохраняется', () => {
  const д = разобрать(ЛИСТ, papa());
  assert.deepEqual([...д.треки.map(т => т.н)], [1, 2, 3, 4, 5, 6, 7]);
  assert.equal(д.треки[0].что, 'Fläschbänkler - das letzte Alphorn');
  assert.equal(д.треки[0].кто, 'Rtur');
  assert.equal(д.треки[6].тип, 'долг ×6');
});

test('чужая страница вместо выгрузки не притворяется очередью', () => {
  assert.throws(() => разобрать('<!doctype html><html>вход</html>', papa()),
    /HTML-страница/);
  assert.throws(() => разобрать('раз,два\nтри,четыре', papa()),
    /не нашёл строку с колонками/);
});
