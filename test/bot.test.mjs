/* ============================================================
   ОТВЕТЧИК ДЛЯ ЧАТА
   ------------------------------------------------------------
   Бот отвечает в чат стрима, и ошибиться там дороже, чем на сайте:
   неверную строку увидят все разом, а исправить её уже нельзя.
   Поэтому он под теми же проверками, что и всё остальное.

   Сервер здесь не поднимается: server.mjs отдаёт свои функции при
   импорте, а данные берёт с локальной копии сайта.
   ============================================================ */

import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { startServer } from './helpers.mjs';

let srv, архив, бот;

before(async () => {
  srv = await startServer();
  process.env.BASE = srv.base;
  бот = await import('../bot/server.mjs');
  архив = await бот.собрать();
});

after(() => srv?.server.close());

test('архив читается с сайта целиком', () => {
  assert.ok(архив.rows.length >= 6500, `разносов ${архив.rows.length}`);
  assert.ok(архив.users.size >= 900, `заказчиков ${архив.users.size}`);
  // бот разбирает данные тем же кодом, что и сайт: шуточных оценок быть не должно
  assert.equal(архив.rows.filter(r => /^гениально\+/.test(r.rate.label)).length, 0);
});

test('находит трек и отвечает коротко', () => {
  const ответ = бот.искатьТрек(архив, 'unravel');
  assert.match(ответ, /Unravel/i);
  assert.match(ответ, /стрим №\d+/);
  // чат Twitch режет длинные сообщения
  assert.ok(ответ.length <= 380, `ответ длиной ${ответ.length}`);
});

test('точное попадание важнее свежести', () => {
  // «Muse — Unravelling» новее, но спрашивают явно не про него
  const ответ = бот.искатьТрек(архив, 'unravel');
  assert.ok(!/Unravelling/i.test(ответ), 'выбран трек с похожим названием вместо точного');
});

test('пробелы в названии не мешают', () => {
  // «KICK BACK» и «KICKBACK» — одна песня, спросить могут любым способом
  const a = бот.искатьТрек(архив, 'kick back');
  const b = бот.искатьТрек(архив, 'kickback');
  assert.match(a, /Kenshi Yonezu/);
  assert.match(b, /Kenshi Yonezu/);
  assert.match(a, /Приносили и раньше/);
});

test('короткий запрос ищется по целому слову', () => {
  // «Ado» не должен цеплять «Shadow» и «Tornado»
  const ответ = бот.искатьТрек(архив, 'Ado');
  const сколько = +(ответ.match(/Ещё (\d+)/) || [])[1];
  assert.ok(сколько < 200, `«Ado» дал ${сколько} совпадений — ищет по подстроке`);
});

test('ненайденное зовёт принести', () => {
  const ответ = бот.искатьТрек(архив, 'ксчйцукенгш');
  assert.match(ответ, /не приносили/);
  assert.match(ответ, /можно нести/);
});

test('пустой запрос объясняет, как спрашивать', () => {
  assert.match(бот.искатьТрек(архив, '  '), /Напиши/);
  assert.match(бот.искатьЗаказчика(архив, ''), /Напиши/);
});

test('статистика заказчика сходится с архивом', () => {
  const [k, hit] = [...архив.users].sort((a, b) => b[1].треки.length - a[1].треки.length)[0];
  const ответ = бот.искатьЗаказчика(архив, hit.имя);
  const треков = +(ответ.match(/(\d+)\s+трек/) || [])[1];
  assert.equal(треков, hit.треки.length);
  assert.match(ответ, /средний \d+\.\d\d/);
  assert.match(ответ, /Место в зачёте: \d+ из \d+/);
  assert.ok(ответ.length <= 380, `ответ длиной ${ответ.length}`);
});

test('неизвестный ник не роняет ответ', () => {
  const ответ = бот.искатьЗаказчика(архив, 'такого-ника-нет');
  assert.match(ответ, /пока ничего не приносил/);
});

test('любой запрос укладывается в длину чата', () => {
  for (const q of ['a', 'о', 'the', 'Ado', 'unravel', 'ost', 'сердце', 'x'.repeat(200)]) {
    const ответ = бот.искатьТрек(архив, q);
    assert.ok(ответ.length <= 380, `«${q}» дал ${ответ.length} символов`);
  }
});

test('каталог опенингов доезжает до бота', () => {
  assert.equal(архив.каталог, true, 'каталог не поднялся — !чтопринести работать не будет');
});

test('«что принести» называет вселенную и чего в ней не хватает', () => {
  const ответ = бот.чтоПринести(архив);
  assert.match(ответ, /разнесли \d+ из \d+/);
  assert.match(ответ, /Не хватает: /);
  assert.ok(ответ.length <= 380, `ответ длиной ${ответ.length}`);
});

test('«что принести» не повторяется на каждом вызове', () => {
  const было = new Set();
  for (let i = 0; i < 15; i++) было.add(бот.чтоПринести(архив).split(':')[0]);
  assert.ok(было.size >= 4, `за пятнадцать вызовов выпало всего ${было.size} вселенных`);
});

test('числа в «что принести» сходятся с каталогом', () => {
  // [...] — массив приезжает из песочницы со своим Array.prototype,
  // и deepEqual считает его чужим даже при одинаковом содержимом
  const почти = [...архив.ctx.almostDone(2)];
  const плохие = почти.slice(0, 10).filter(x =>
    x.нехватает.length !== x.нет || x.got + x.нет !== x.всего);
  assert.deepEqual([...плохие.map(x => x.name)], [],
    'счётчик не сходится со списком недостающих');
});


test('в ответе есть ссылка на сам разнос', () => {
  // ради неё вопрос чаще всего и задают: послушать разбор, а не
  // только узнать оценку
  for (const q of ['unravel', 'kickback', 'bad apple']) {
    const ответ = бот.искатьТрек(архив, q);
    assert.match(ответ, /Разнос: https?:\/\//, `«${q}» без ссылки на разнос`);
    assert.ok(ответ.length <= 380, `«${q}» дал ${ответ.length} символов`);
  }
});

test('ник из твича ищется, даже если в таблице записан иначе', () => {
  const [, hit] = [...архив.users].sort((a, b) => b[1].треки.length - a[1].треки.length)[0];
  // кусок ника — человек в чате зовётся не так, как записан в таблице
  const кусок = hit.имя.replace(/^@/, '').slice(0, 5);
  const ответ = бот.искатьЗаказчика(архив, кусок);
  assert.ok(/трек|Похожие/.test(ответ), `по «${кусок}» бот ничего не предложил`);
  // и не врёт «ничего не приносил», когда просто не нашёл точного
  assert.ok(!/^\S+ пока ничего не приносил\.$/.test(ответ));
});
