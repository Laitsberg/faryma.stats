const ЖИВЁТ_MS = +(process.env.QUEUE_TTL_SEC || 60) * 1000;

let КЭШ = null;      // { когда, данные }
let ГРУЗИМ = null;   // чтобы десять запросов не превратились в десять походов

/* ---------- papaparse ----------
   Берём его с сайта, как и всё остальное: своей копии у бота нет,
   иначе она разойдётся с той, что стоит на странице. */
let PAPA = null;
async function papa(base) {
  if (PAPA) return PAPA;
  const r = await fetch(`${base}/vendor/papaparse.min.js`,
    { headers: { 'user-agent': 'faryma-chat-bot' } });
  if (!r.ok) throw new Error(`papaparse: ответил ${r.status}`);
  const песочница = { module: { exports: {} }, exports: {}, window: {}, global: {} };
  vm.createContext(песочница);
  vm.runInContext(await r.text(), песочница, { filename: 'papaparse' });
  PAPA = песочница.module.exports?.parse ? песочница.module.exports
    : песочница.Papa || песочница.window.Papa;
  return PAPA;
}

/* ---------- разбор ---------- */

/* Заголовок ищем, а не берём первой строкой. Над таблицей висят
   объявления и списки донатеров, и они переезжают: сегодня шапка
   в первой строке, завтра кто-то вставит строку выше. Ищем строку,
   в которой одновременно есть «Что» и «Тип» — других таких нет. */
function найтиШапку(строки) {
  for (let i = 0; i < Math.min(строки.length, 40); i++) {
    const яч = строки[i].map(я => я.текст.trim().toLowerCase());
    if (яч.includes('что') && яч.includes('тип')) return i;
  }
  return -1;
}

/* «долг x8», «Долг Х8», «долг х 8» — одно и то же. Кириллическая «х»
   и латинская «x» в таблице встречаются вперемешку, поэтому смотрим
   на цифру, а не на букву.

   Бывает и просто «долг», без множителя — это долг ×1, так сказал
   владелец таблицы. Пишем его как «долг ×1», чтобы он не выглядел
   отдельным сортом и встал на своё место: последним из долгов.

   Само число — это не сорт, а срок ожидания: что не разобрали в
   субботу, поднимается на ступень выше, и ×8 назавтра станет ×9. */
export function разобратьТип(сырой) {
  const t = String(сырой || '').trim();
  if (!t) return null;
  const низ = t.toLowerCase().replace(/\s+/g, ' ');
  const долг = низ.match(/долг\s*[xх]?\s*(\d+)/);
  if (долг) return { вид: 'долг', кратность: +долг[1], подпись: `долг ×${долг[1]}` };
  // \b тут не годится: для регулярки кириллическая «г» не буква,
  // и границы слова после «долг» она не видит вовсе
  if (/^долг(?:\s|$)/.test(низ)) return { вид: 'долг', кратность: 1, подпись: 'долг ×1' };
  if (/донат/.test(низ))  return { вид: 'донат',  кратность: null, подпись: 'донат' };
  if (/повтор/.test(низ)) return { вид: 'повтор', кратность: null, подпись: 'повтор' };
  if (/заказ/.test(низ))  return { вид: 'заказ',  кратность: null, подпись: 'заказ' };
  return { вид: 'прочее', кратность: null, подпись: t };
}

/* Дата ближайшего стрима написана словами: «Стрим на 5.09.2026г.»
   Ищем по всему листу, а не только выше таблицы: строка колонок в
   этом листе стоит самой первой, а объявления висят под ней. */
function найтиДату(строки) {
  for (const строка of строки)
    for (const я of строка) {
      const m = я.текст.match(/стрим\s+на\s+(\d[\d.]*\d)/i);
      if (m) return m[1].replace(/\.$/, '');
    }
  return '';
}

/* Общий разбор для обоих источников. На вход — таблица ячеек вида
   { текст, цвет }; у CSV цвет всегда пустой, и тогда пометок просто
   не будет. */
export function собрать(таблица) {
  const шапка = найтиШапку(таблица);
  if (шапка < 0)
    throw new Error('не нашёл строку с колонками «Что» и «Тип» — это точно тот лист?');

  const имена = таблица[шапка].map(я => я.текст.trim());
  const где = имя => имена.findIndex(x => x.toLowerCase() === имя);
  const кол = {
    что: где('что'), кто: где('кто'), тип: где('тип'),
    откуда: где('откуда'), жанр: где('жанр'),
    инфа: имена.findIndex(x => /доп\.?\s*инфа/i.test(x)),
    // У цены берём только цвет: жёлтая, зелёная и красная заливка
    // размечают порядок разбора. Текст этой ячейки не читается нигде.
    ценаЦвет: где('цена')
  };

  const треки = [];
  for (let i = шапка + 1; i < таблица.length; i++) {
    const р = таблица[i] || [];
    const яч = н => (н >= 0 && р[н]) ? р[н].текст.trim() : '';
    const что = яч(кол.что);
    const тип = разобратьТип(яч(кол.тип));
    // Строки-объявления над таблицей и пустые хвосты: у них нет типа.
    // Тип есть только у настоящей заявки, поэтому он и служит ситом.
    if (!что || !тип) continue;

    const цветЦены = кол.ценаЦвет >= 0 && р[кол.ценаЦвет]
      ? р[кол.ценаЦвет].цвет : '';
    треки.push({
      что,
      кто:    яч(кол.кто),
      откуда: яч(кол.откуда),
      жанр:   яч(кол.жанр),
      инфа:   яч(кол.инфа),
      вид: тип.вид, кратность: тип.кратность, тип: тип.подпись,
      пометка: пометкаПоЦвету(цветЦены),
      // номер строки в листе — по нему очередь остаётся в исходном
      // порядке, даже если страница потом что-то перегруппирует
      н: треки.length + 1
    });
  }

  const группы = {};
  for (const т of треки) группы[т.тип] = (группы[т.тип] || 0) + 1;

  return {
    стрим: найтиДату(таблица),
    всего: треки.length,
    группы,
    треки,
    // есть ли вообще пометки: страница по этому решает, показывать
    // ли колонку. Публикацию могут отключить, и тогда их не будет
    пометки: треки.filter(т => т.пометка).length,
    обновлено: new Date().toISOString()
  };
}

/* CSV → та же таблица ячеек, только без цветов. */
export function изCsv(текст, P) {
  if (/^\s*<(!doctype|html)/i.test(текст))
    throw new Error('вернулась HTML-страница, а не CSV — похоже, доступ к листу закрыт');
  return P.parse(текст, { skipEmptyLines: false }).data
    .map(строка => строка.map(x => ({ текст: String(x || ''), цвет: '' })));
}

/* ---------- загрузка ---------- */

async function достать(адрес) {
  const r = await fetch(адрес, { headers: { 'user-agent': 'faryma-chat-bot' } });
  if (!r.ok) throw new Error(`ответил ${r.status}`);
  return r.text();
}

const коротко = а => а.replace(/\?.*/, '?…');

async function загрузить(base) {
  const беды = [];

  // сперва опубликованная страница: только в ней есть цвета
  try {
    const д = собрать(сетка(await достать(PUB)));
    д.источник = 'опубликованный лист';
    return д;
  } catch (e) { беды.push(`публикация: ${e.message}`); }

  const P = await papa(base);
  for (const адрес of CSV) {
    try {
      const д = собрать(изCsv(await достать(адрес), P));
      д.источник = коротко(адрес);
      return д;
    } catch (e) { беды.push(`${коротко(адрес)}: ${e.message}`); }
  }
  throw new Error('очередь не прочиталась: ' + беды.join('; '));
}

export async function очередь(base) {
  if (КЭШ && Date.now() - КЭШ.когда < ЖИВЁТ_MS) return КЭШ.данные;
  if (!ГРУЗИМ) {
    ГРУЗИМ = загрузить(base)
      .then(д => { КЭШ = { когда: Date.now(), данные: д }; return д; })
      .finally(() => { ГРУЗИМ = null; });
  }
  return ГРУЗИМ;
}

/* Что бот увидел в листе на самом деле. Нужен, когда что-то не сходится:
   строение листа отсюда не проверить, а гадать о нём нельзя.
   Цены не показывает и здесь — только цвета их ячеек. */
export async function разведка(base) {
  const отчёт = { источники: [] };

  const разобрать = async (имя, взять) => {
    const п = { имя };
    try {
      const таблица = await взять();
      п.строкВсего = таблица.length;
      п.шапкаВСтроке = найтиШапку(таблица);
      п.колонки = п.шапкаВСтроке >= 0
        ? таблица[п.шапкаВСтроке].map(я => я.текст.trim()) : null;
      if (п.шапкаВСтроке >= 0) {
        const д = собрать(таблица);
        п.дата = д.стрим;
        п.треков = д.всего;
        п.виды = д.группы;
        п.сПометкой = д.пометки;
        п.пометок = {};
        for (const т of д.треки) if (т.пометка)
          п.пометок[т.пометка] = (п.пометок[т.пометка] || 0) + 1;
        п.примеры = д.треки.slice(0, 5);
        п.непонятые = [...new Set(д.треки.filter(т => т.вид === 'прочее')
          .map(т => т.тип))].slice(0, 20);
      }
    } catch (e) { п.беда = e.message; }
    отчёт.источники.push(п);
  };

  await разобрать('опубликованный лист', async () => сетка(await достать(PUB)));
  const P = await papa(base);
  for (const адрес of CSV)
    await разобрать(коротко(адрес), async () => изCsv(await достать(адрес), P));

  return отчёт;
}
