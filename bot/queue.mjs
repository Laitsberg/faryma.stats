/* ============================================================
   ОЧЕРЕДЬ НА РАЗНОС
   ------------------------------------------------------------
   Читает вкладку «На разнос» той же таблицы, что и архив, и
   отдаёт её странице сайта.

   Почему через бота, а не напрямую из браузера: очередь заполняют
   прямо во время стрима, и утренняя копия соврала бы ровно тогда,
   когда на неё смотрят. Бот держит выгрузку минуту и обновляет
   сам — этого хватает, чтобы список был живым, и мало, чтобы
   Гугл начал ругаться на частоту.

   ЦЕНЫ ОТСЮДА НЕ ВЫХОДЯТ. Из колонки «Цена» берётся только цвет
   заливки, само значение не читается вовсе. В таблице сумму видит
   тот, кто открыл таблицу; на сайте это стало бы удобным для чтения
   списком «кто сколько заплатил», и владелец решил, что не надо.

   Источников два, и порядок важен:

   1. Опубликованная веб-страница листа. Из неё приезжает и текст,
      и заливка — а заливка тут значит очень много: жёлтая «сейчас
      разбирают», зелёная «следующий», красная «через одного».
   2. Обычная CSV-выгрузка. Цветов в ней нет по природе формата,
      зато она работает, даже если публикацию отключат. Запасной
      путь: список будет, пометок не будет.
   ============================================================ */

