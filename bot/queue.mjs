/* ============================================================
   ОЧЕРЕДЬ НА РАЗНОС
   ------------------------------------------------------------
   Читает вкладку «На разнос» той же таблицы, что и архив, и
   отдаёт её страницей сайта.

   Почему через бота, а не напрямую из браузера: очередь заполняют
   прямо во время стрима, и утренняя копия соврала бы ровно тогда,
   когда на неё смотрят. Бот держит выгрузку минуту и обновляет
   сам — этого хватает, чтобы список был живым, и мало, чтобы
   Гугл начал ругаться на частоту.

   ЦЕНЫ ОТСЮДА НЕ ВЫХОДЯТ. Колонка «Цена» выбрасывается при разборе
   и в ответ не попадает ни в каком виде. В таблице её видит тот,
   кто открыл таблицу; на сайте это стало бы удобным для чтения
   списком «кто сколько заплатил», и владелец решил, что не надо.

   Чего тут принципиально нет — цвета. Жёлтая, зелёная и красная
   заливка в таблице означают «разбирают сейчас», «следующий» и
   «через одного», но CSV несёт только значения ячеек: заливка в
   выгрузку не попадает. Чтобы её достать, лист надо отдельно
   опубликовать как веб-страницу — тогда цвет приезжает в разметке.
   Пока этого нет, порядок показываем без пометок.
   ============================================================ */

import vm from 'node:vm';

const SHEET_ID = process.env.QUEUE_SHEET_ID
  || '1yEUr29llt9L1zWavC4lxkyhd6UeIwrQuGsPon9fXt4A';
const GID = process.env.QUEUE_GID || '823158240';

/* Те же два адреса, что и у скачивателя архива: у разных способов
   публикации работает разное, первый осмысленный ответ выигрывает. */
const АДРЕСА = process.env.QUEUE_CSV_URL ? [process.env.QUEUE_CSV_URL] : [
  `https://docs.google.com/spreadsheets/d/${SHEET_ID}/export?format=csv&gid=${GID}`,
  `https://docs.google.com/spreadsheets/d/${SHEET_ID}/gviz/tq?tqx=out:csv&gid=${GID}&headers=0`
];

const ЖИВЁТ_MS = +(process.env.QUEUE_TTL_SEC || 60) * 1000;

let КЭШ = null;      // { когда, данные }
let ГРУЗИМ = null;   // чтобы десять запросов не превратились в десять походов

/* ---------- papaparse ----------
   Берём его с сайта, как и всё остальное: своей копии у бота нет,
   иначе она разойдётся с той, что стоит на странице. */
let PAPA = null;
async function papa(base) {
  if (PAPA) return PAPA;
  const r = await fetch(`${base}/vendor/papaparse.min.js`,
    { headers: { 'user-agent': 'faryma-chat-bot' } });
  if (!r.ok) throw new Error(`papaparse: ответил ${r.status}`);
  const песочница = { module: { exports: {} }, exports: {}, window: {}, global: {} };
  vm.createContext(песочница);
  vm.runInContext(await r.text(), песочница, { filename: 'papaparse' });
  PAPA = песочница.module.exports?.parse ? песочница.module.exports
    : песочница.Papa || песочница.window.Papa;
  return PAPA;
}

/* ---------- разбор ---------- */

/* Заголовок ищем, а не берём первой строкой. Над таблицей висят
   объявления и списки донатеров, и они переезжают: сегодня шапка
   в первой строке, завтра кто-то вставит строку выше. Ищем строку,
   в которой одновременно есть «Что» и «Тип» — других таких нет. */
function найтиШапку(строки) {
  for (let i = 0; i < Math.min(строки.length, 40); i++) {
    const яч = строки[i].map(x => String(x || '').trim().toLowerCase());
    if (яч.includes('что') && яч.includes('тип')) return i;
  }
  return -1;
}

/* «долг x8», «Долг Х8», «долг х 8» — одно и то же. Кириллическая «х»
   и латинская «x» в таблице встречаются вперемешку, поэтому смотрим
   на цифру, а не на букву. */
export function разобратьТип(сырой) {
  const t = String(сырой || '').trim();
  if (!t) return null;
  const низ = t.toLowerCase().replace(/\s+/g, ' ');
  const долг = низ.match(/долг\s*[xх]?\s*(\d+)/);
  if (долг) return { вид: 'долг', кратность: +долг[1], подпись: `долг ×${долг[1]}` };
  if (/донат/.test(низ))  return { вид: 'донат',  кратность: null, подпись: 'донат' };
  if (/повтор/.test(низ)) return { вид: 'повтор', кратность: null, подпись: 'повтор' };
  if (/заказ/.test(низ))  return { вид: 'заказ',  кратность: null, подпись: 'заказ' };
  return { вид: 'прочее', кратность: null, подпись: t };
}

/* Дата ближайшего стрима написана словами: «Стрим на 5.09.2026г.»
   Ищем по всему листу, а не только выше таблицы: строка колонок в
   этом листе стоит самой первой, а объявления висят под ней. */
function найтиДату(строки) {
  for (const строка of строки)
    for (const яч of строка) {
      const m = String(яч || '').match(/стрим\s+на\s+(\d[\d.]*\d)/i);
      if (m) return m[1].replace(/\.$/, '');
    }
  return '';
}

/* Разбор отдельно от загрузки: так его проверяют на выдуманном
   листе, без похода в сеть. */
export function разобрать(текст, P) {
  if (/^\s*<(!doctype|html)/i.test(текст))
    throw new Error('вернулась HTML-страница, а не CSV — похоже, доступ к листу закрыт');

  const строки = P.parse(текст, { skipEmptyLines: false }).data;
  const шапка = найтиШапку(строки);
  if (шапка < 0)
    throw new Error('не нашёл строку с колонками «Что» и «Тип» — это точно тот лист?');

  const имена = строки[шапка].map(x => String(x || '').trim());
  const где = имя => имена.findIndex(x => x.toLowerCase() === имя);
  const кол = {
    что: где('что'), кто: где('кто'), тип: где('тип'),
    откуда: где('откуда'), жанр: где('жанр'), инфа: имена.findIndex(
      x => /доп\.?\s*инфа/i.test(x))
  };
  // «Цена» намеренно не ищется: чего нет в разборе, то не утечёт в ответ

  const треки = [];
  for (let i = шапка + 1; i < строки.length; i++) {
    const р = строки[i] || [];
    const что = String(р[кол.что] || '').trim();
    const тип = разобратьТип(р[кол.тип]);
    // Строки-объявления над таблицей и пустые хвосты: у них нет типа.
    // Тип есть только у настоящей заявки, поэтому он и служит ситом.
    if (!что || !тип) continue;
    треки.push({
      что,
      кто:    String(р[кол.кто]    || '').trim(),
      откуда: String(р[кол.откуда] || '').trim(),
      жанр:   String(р[кол.жанр]   || '').trim(),
      инфа:   кол.инфа >= 0 ? String(р[кол.инфа] || '').trim() : '',
      вид: тип.вид, кратность: тип.кратность, тип: тип.подпись,
      // номер строки в листе — по нему очередь остаётся в исходном
      // порядке, даже если страница потом что-то перегруппирует
      н: треки.length + 1
    });
  }

  const группы = {};
  for (const т of треки) группы[т.тип] = (группы[т.тип] || 0) + 1;

  return {
    стрим: найтиДату(строки),
    всего: треки.length,
    группы,
    треки,
    обновлено: new Date().toISOString()
  };
}

/* ---------- загрузка ---------- */

async function загрузить(base) {
  const P = await papa(base);
  const беды = [];
  for (const адрес of АДРЕСА) {
    try {
      const r = await fetch(адрес, { headers: { 'user-agent': 'faryma-chat-bot' } });
      if (!r.ok) { беды.push(`${r.status} на ${адрес.replace(/\?.*/, '?…')}`); continue; }
      const данные = разобрать(await r.text(), P);
      данные.источник = адрес.replace(/\?.*/, '?…');
      return данные;
    } catch (e) { беды.push(e.message); }
  }
  throw new Error('очередь не прочиталась: ' + беды.join('; '));
}

export async function очередь(base) {
  if (КЭШ && Date.now() - КЭШ.когда < ЖИВЁТ_MS) return КЭШ.данные;
  if (!ГРУЗИМ) {
    ГРУЗИМ = загрузить(base)
      .then(д => { КЭШ = { когда: Date.now(), данные: д }; return д; })
      .finally(() => { ГРУЗИМ = null; });
  }
  return ГРУЗИМ;
}

/* Что бот увидел в листе на самом деле. Нужен один раз, при первом
   запуске: строение листа отсюда не проверить, а гадать о нём нельзя.
   Цены не показывает и здесь. */
export async function разведка(base) {
  const P = await papa(base);
  const отчёт = { адреса: [] };
  for (const адрес of АДРЕСА) {
    const п = { адрес: адрес.replace(/\?.*/, '?…') };
    try {
      const r = await fetch(адрес, { headers: { 'user-agent': 'faryma-chat-bot' } });
      п.ответ = r.status;
      if (r.ok) {
        const текст = await r.text();
        п.байт = текст.length;
        const строки = P.parse(текст, { skipEmptyLines: false }).data;
        const шапка = найтиШапку(строки);
        п.строкВсего = строки.length;
        п.шапкаВСтроке = шапка;
        п.колонки = шапка >= 0 ? строки[шапка].map(x => String(x || '').trim()) : null;
        if (шапка >= 0) {
          const д = разобрать(текст, P);
          п.дата = д.стрим;
          п.треков = д.всего;
          п.виды = д.группы;
          // первые пять — посмотреть, что вообще приезжает
          п.примеры = д.треки.slice(0, 5);
          // всё, что тип не узнал: если тут пусто, разбор полон
          п.непонятые = [...new Set(д.треки.filter(т => т.вид === 'прочее')
            .map(т => т.тип))].slice(0, 20);
        }
      }
    } catch (e) { п.беда = e.message; }
    отчёт.адреса.push(п);
  }
  return отчёт;
}
