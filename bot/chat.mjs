/* ============================================================
   КТО СЕЙЧАС В ЧАТЕ
   ------------------------------------------------------------
   Держит соединение с чатом стрима и запоминает, кто писал за
   последний час. Этот список забирает колесо на сайте — чтобы
   не переносить участников розыгрыша руками.

   Ключей Twitch тут нет и не нужно: в чат можно войти анонимно,
   назвавшись justinfan с любым числом. Такой гость умеет только
   читать, что нам и требуется.

   Сообщения не сохраняются — только ник и время последней реплики.
   Колесу нужен список имён, а переписка зрителей нас не касается.
   ============================================================ */

import net from 'node:net';

const HOST   = process.env.CHAT_HOST || 'irc.chat.twitch.tv';
const PORT   = +(process.env.CHAT_PORT || 6667);
const КАНАЛ  = (process.env.TWITCH_CHANNEL || 'farymacomposer').toLowerCase();
/* За сколько минут считаем человека «сейчас в чате». Читается при
   каждом обращении, а не один раз при запуске: так настройку можно
   поменять на ходу, не перезапуская сервис. */
const окно = () => +(process.env.CHAT_WINDOW_MIN || 60) * 60_000;

/* Боты каналов сами пишут в чат, но крутить их в колесе незачем */
const БОТЫ = new Set([
  'moobot', 'nightbot', 'streamelements', 'streamlabs', 'wizebot',
  'fossabot', 'sery_bot', 'own3d', 'soundalerts', 'kofistreambot'
]);

const писали = new Map();       // ник → когда написал в последний раз
let сокет = null;
let живо = false;
let попытка = 0;
let последняяСтрока = 0;
let остановлено = false;        // после сброса не переподключаемся
let таймер = null;

function убратьСтарых() {
  const край = Date.now() - окно();
  for (const [ник, когда] of писали) if (когда < край) писали.delete(ник);
}

/* Строка чата выглядит так:
   :ник!ник@ник.tmi.twitch.tv PRIVMSG #канал :текст сообщения
   Нам нужен только ник — до восклицательного знака. */
function разобрать(строка) {
  if (строка.startsWith('PING')) return { pong: строка.slice(5) };
  const m = строка.match(/^:([^!]+)![^ ]+ PRIVMSG #\S+ :/);
  return m ? { ник: m[1] } : null;
}

function подключиться() {
  if (сокет) { сокет.destroy(); сокет = null; }

  сокет = net.createConnection({ host: HOST, port: PORT }, () => {
    живо = true;
    попытка = 0;
    // анонимный гость: пароль не нужен, имя — justinfan с любым числом
    сокет.write(`NICK justinfan${10000 + Math.floor(Math.random() * 80000)}\r\n`);
    сокет.write(`JOIN #${КАНАЛ}\r\n`);
    console.log(`чат #${КАНАЛ}: подключились`);
  });

  let хвост = '';
  сокет.setEncoding('utf8');
  сокет.on('data', кусок => {
    последняяСтрока = Date.now();
    хвост += кусок;
    const строки = хвост.split('\r\n');
    хвост = строки.pop();          // последняя может быть недописанной
    for (const строка of строки) {
      const it = разобрать(строка);
      if (!it) continue;
      if (it.pong) { сокет.write(`PONG ${it.pong}\r\n`); continue; }
      const ник = it.ник.toLowerCase();
      if (БОТЫ.has(ник) || ник.startsWith('justinfan')) continue;
      писали.set(it.ник, Date.now());     // пишем как есть, с регистром
      if (писали.size > 5000) убратьСтарых();
    }
  });

  const заново = причина => {
    if (остановлено) return;
    if (!живо && попытка > 0) return;      // уже переподключаемся
    живо = false;
    сокет?.destroy();
    сокет = null;
    // ждём всё дольше, но не больше минуты: чат может лежать долго
    const пауза = Math.min(60_000, 2000 * Math.pow(2, попытка++));
    console.log(`чат #${КАНАЛ}: ${причина}, вернусь через ${Math.round(пауза / 1000)} с`);
    таймер = setTimeout(подключиться, пауза);
    таймер.unref?.();
  };

  сокет.on('error', e => заново('ошибка ' + e.message));
  сокет.on('close', () => заново('соединение закрылось'));
  сокет.setTimeout(10 * 60_000, () => заново('десять минут тишины'));
}

/* ---------- наружу ---------- */

export function начать() {
  остановлено = false;
  if (!сокет) подключиться();
}

export function чатеры() {
  убратьСтарых();
  // свежие первыми: кто писал только что, тот точно смотрит
  return [...писали].sort((a, b) => b[1] - a[1]).map(([ник]) => ник);
}

export function состояние() {
  убратьСтарых();
  return {
    канал: КАНАЛ,
    подключены: живо,
    человек: писали.size,
    окноМинут: окно() / 60_000,
    тишинаСекунд: последняяСтрока ? Math.round((Date.now() - последняяСтрока) / 1000) : null
  };
}

/* Остановить чтение и забыть накопленное.
   Флаг «остановлено» тут не для красоты: без него закрытие сокета
   считалось обрывом связи, и чат начинал переподключаться заново —
   уже к тому, кого мы только что выключили. */
export function сброс() {
  остановлено = true;
  if (таймер) { clearTimeout(таймер); таймер = null; }
  писали.clear();
  if (сокет) { сокет.destroy(); сокет = null; }
  живо = false; попытка = 0;
}
