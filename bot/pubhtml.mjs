/* ============================================================
   ОПУБЛИКОВАННЫЙ ЛИСТ → СЕТКА ЯЧЕЕК С ЦВЕТОМ
   ------------------------------------------------------------
   CSV несёт только значения, а нам нужна ещё и заливка: жёлтая
   означает «разбирают сейчас», зелёная «следующий», красная «через
   одного». Заливка приезжает только в опубликованной веб-странице
   листа (Файл → Опубликовать в интернете), её тут и разбираем.

   Разбираем регулярками, а не настоящим разборщиком HTML: страницу
   генерирует Гугл, она однообразна до последнего пробела, а тащить
   в бота зависимость ради одного файла не хочется. Взамен —
   проверки на выдуманной странице той же формы.

   Цвет лежит не в самой ячейке, а в классе: наверху страницы стоит
   <style> с правилами вида «.s12{background-color:#ffff00}», а у
   ячейки только class="s12". Поэтому сначала собираем таблицу
   классов, потом читаем ячейки.
   ============================================================ */

/* ---------- цвета ---------- */

function вHsl(hex) {
  const s = hex.replace('#', '');
  const п = s.length === 3 ? s.split('').map(c => c + c).join('') : s;
  if (!/^[0-9a-f]{6}$/i.test(п)) return null;
  const r = parseInt(п.slice(0, 2), 16) / 255;
  const g = parseInt(п.slice(2, 4), 16) / 255;
  const b = parseInt(п.slice(4, 6), 16) / 255;
  const макс = Math.max(r, g, b), мин = Math.min(r, g, b), д = макс - мин;
  const l = (макс + мин) / 2;
  if (!д) return { h: 0, s: 0, l };
  const s2 = д / (1 - Math.abs(2 * l - 1));
  let h;
  if (макс === r)      h = ((g - b) / д) % 6;
  else if (макс === g) h = (b - r) / д + 2;
  else                 h = (r - g) / д + 4;
  h = (h * 60 + 360) % 360;
  return { h, s: s2, l };
}

/* Какой цвет что означает. Границы широкие намеренно: в таблице
   красят вручную, и «жёлтый» у одного модератора выйдет чуть
   оранжевее, чем у другого. Белое, серое и чёрное — это отсутствие
   пометки, а не пометка: у неокрашенных ячеек фон именно такой. */
export function пометкаПоЦвету(hex) {
  const c = hex && вHsl(hex);
  if (!c) return null;
  if (c.s < 0.25 || c.l > 0.93 || c.l < 0.12) return null;
  if (c.h >= 40 && c.h <= 75)   return 'сейчас';
  if (c.h > 75 && c.h <= 170)   return 'следующий';
  if (c.h >= 330 || c.h <= 20)  return 'потом';
  return null;
}

/* ---------- таблица классов ---------- */

function классыСЦветом(html) {
  const стили = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)]
    .map(m => m[1]).join('\n');
  const карта = new Map();
  // «.ritz .waffle .s12{background-color:#ffff00;...}» — берём последний
  // класс перед фигурной скобкой и цвет фона из тела правила
  for (const m of стили.matchAll(/\.([A-Za-z0-9_-]+)\s*\{([^}]*)\}/g)) {
    const цвет = m[2].match(/background-color\s*:\s*(#[0-9a-f]{3,6})/i);
    if (цвет) карта.set(m[1], цвет[1].toLowerCase());
  }
  return карта;
}

/* ---------- текст ячейки ---------- */

const СУЩНОСТИ = {
  '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"',
  '&#39;': "'", '&nbsp;': ' ', '&apos;': "'"
};

function текстЯчейки(html) {
  return html
    .replace(/<br\s*\/?>/gi, ' ')
    .replace(/<[^>]+>/g, '')
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n))
    .replace(/&[a-z]+;|&#39;/gi, э => СУЩНОСТИ[э.toLowerCase()] ?? э)
    .replace(/\s+/g, ' ')
    .trim();
}

/* ---------- сетка ---------- */

/* Отдаём таблицу ячеек: у каждой текст и цвет фона. Дальше её читает
   тот же разбор, что и CSV, — там, где цвета нет, он просто пустой. */
export function сетка(html) {
  if (!/<table/i.test(html))
    throw new Error('в опубликованной странице нет таблицы — тот ли это адрес?');

  const классы = классыСЦветом(html);
  const строки = [];

  for (const стр of html.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/gi)) {
    const ячейки = [];
    for (const я of стр[1].matchAll(/<t([dh])([^>]*)>([\s\S]*?)<\/t\1>/gi)) {
      // Номера строк слева — служебные, их в таблице быть не должно
      if (/row-headers?-background|freezebar/i.test(я[2])) continue;
      const кл = (я[2].match(/class\s*=\s*"([^"]*)"/i) || [, ''])[1].split(/\s+/);
      const цвет = кл.map(k => классы.get(k)).find(Boolean) || '';
      const ячейка = { текст: текстЯчейки(я[3]), цвет };
      // colspan сдвигает колонки: без него объединённая шапка съезжает,
      // и «Тип» оказывается там, где на самом деле «Цена»
      const span = +(я[2].match(/colspan\s*=\s*"?(\d+)/i) || [, 1])[1] || 1;
      ячейки.push(ячейка);
      for (let i = 1; i < span; i++) ячейки.push({ текст: '', цвет });
    }
    if (ячейки.length) строки.push(ячейки);
  }

  if (!строки.length) throw new Error('в опубликованной странице нет строк');
  return строки;
}
